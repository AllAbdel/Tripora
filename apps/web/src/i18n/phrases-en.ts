/** « nature et paysages et détente » → les envies une par une (certaines contiennent « et »). */
function envies(texte: string): string[] | null {
  const reste = texte.toLowerCase();
  const sortie: string[] = [];
  let i = 0;
  const cles = Object.keys(ENVIES).sort((a, b) => b.length - a.length);
  while (i < reste.length) {
    const cle = cles.find((c) => reste.startsWith(c, i));
    if (!cle) return null;
    sortie.push(ENVIES[cle]!);
    i += cle.length;
    if (reste.startsWith(' et ', i)) i += 4;
    else if (reste.startsWith(', ', i)) i += 2;
    else if (i < reste.length) return null;
  }
  return sortie;
}

