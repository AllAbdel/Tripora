/** Une raison de la note, en gardant sa casse de départ ; null si on ne la connaît pas. */
function raisonDeNote(texte: string): string | null {
  for (const [motif, remplacement] of RAISONS) {
    const trouve = motif.exec(texte);
    if (!trouve) continue;
    const anglais = typeof remplacement === 'string' ? texte.replace(motif, remplacement) : remplacement(...trouve.slice(1));
    if (anglais === null) continue;
    return /^\p{Lu}/u.test(texte) ? anglais.charAt(0).toUpperCase() + anglais.slice(1) : anglais;
  }
  return null;
}

/** « a, b » : deux raisons collées par une virgule, alors qu'une raison peut elle-même en contenir. */
function deuxRaisons(texte: string): string | null {
  const seule = raisonDeNote(texte);
  if (seule) return seule;
  const morceaux = texte.split(', ');
  for (let i = 1; i < morceaux.length; i += 1) {
    const a = raisonDeNote(morceaux.slice(0, i).join(', '));
    const b = a && raisonDeNote(morceaux.slice(i).join(', '));
    if (a && b) return `${a}, ${b}`;
  }
  return null;
}

/**
 * Une suite « a · b · c » dont chaque morceau se traduit seul — par l'une des
 * règles données, ou par le dictionnaire entier (phrases et motifs). `null` si un morceau résiste :
 * mieux vaut la ligne entière en français qu'un mélange.
 */
function parMorceaux(t: Traducteur, texte: string, regles: readonly Motif[] = []): string | null {
  const morceaux = texte.split(' · ');
  if (morceaux.length < 2) return null;
  const sortie = morceaux.map((morceau) => {
    const connu = t(morceau);
    if (connu !== null) return connu;
    for (const [motif, remplacement] of regles) {
      const trouve = motif.exec(morceau);
      if (!trouve) continue;
      const compose = typeof remplacement === 'string'
        ? morceau.replace(motif, remplacement)
        : remplacement(t, ...trouve.slice(1).map((g) => g ?? ''));
      if (compose !== null) return compose;
    }
    // Un morceau sans « · » : les motifs de tout le dictionnaire s'y essaient (sans boucler sur celui-ci).
    return traduireCle({ phrases: PHRASES, motifs: MOTIFS }, morceau);
  });
  return sortie.every((morceau) => morceau !== null) ? sortie.join(' · ') : null;
}

/** Une ligne de réservation : « Booking.com · arrivée 14 h → départ jeu. 16 juil. 12 h · 3 nuits ». */
function ligneDeReservation(texte: string): string | null {
  const morceaux = texte.split(' · ');
  let reconnus = 0;
  const sortie = morceaux.map((morceau, i) => {
    let r: RegExpExecArray | null;
    if ((r = /^(\d+) nuits?$/u.exec(morceau))) {
      reconnus += 1;
      return `${r[1]} ${nombre(r[1]!, 'night', 'nights')}`;
    }
    // Une heure ou une date (un chiffre au moins) après « arrivée » et « départ » : pas « départ de Paris ».
    if ((r = /^(?:arrivée ((?=[^→]*\p{Nd}).{1,12}?))?(?:(?: → )?départ ((?=.*\p{Nd})(?!de |d’).{1,30}))?$/u.exec(morceau)) && (r[1] || r[2])) {
      reconnus += 1;
      return [r[1] ? `check-in ${r[1]}` : null, r[2] ? `check-out ${r[2]}` : null].filter(Boolean).join(' → ');
    }
    if ((r = /^(\p{Nd}{1,2}(?:[:.]\p{Nd}{2}| h(?: \p{Nd}{2})?)?(?: ?[AP]M)?)? ?jusqu’(?:au|à) ([^.]{1,24}|[^ ]+\. \p{Nd}{1,2} [^ ]+\.?)$/u.exec(morceau))) {
      reconnus += 1;
      return `${r[1] ? `${r[1]} ` : ''}until ${r[2]}`;
    }
    // Le premier morceau peut être le nom du site (Booking.com, Airbnb…).
    return i === 0 ? morceau : null;
  });
  return reconnus > 0 && sortie.every((morceau) => morceau !== null) ? sortie.join(' · ') : null;
}

