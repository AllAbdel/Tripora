/**
 * L'anglais de la traduction au rendu (voir `traductionAuRendu.ts`) : le
 * modèle des autres langues (guide : `docs/TRADUCTIONS.md`).
 *
 * La clé est la phrase française telle qu'elle s'affiche, espaces resserrés ;
 * la valeur, sa traduction. Les motifs traduisent les phrases qui portent un
 * nombre ou un nom : ancrés (^…$), essayés dans l'ordre après les phrases
 * exactes ; une fonction peut renoncer (`null`) et laisser passer le suivant.
 * Les plus récents sont en tête de la liste : un motif ajouté passe avant les
 * motifs larges du bas (explications du classement, dates).
 *
 * Vocabulaire tenu partout : « trip » pour voyage, « wishes » pour les
 * envies, « vault » pour le coffre, « people » pour les participants, comme `textes.ts`.
 * Montants, dates, températures et distances arrivent déjà dans la langue et
 * les unités de la personne (`regional.ts`) : les motifs les recopient.
 *
 * Un motif large (« X doit Y à Z ») doit se contraindre — un chiffre, une
 * longueur — ou passer par `complement()` : sinon il traduit trois mots d'une
 * phrase qu'il n'a jamais vue. `phrases-en.test.ts` garde les cas connus.
 *
 * Pour compléter : `traductions:extraire` (le code) et `traductions:recolte`
 * (l'écran) listent ce qui reste en français.
 */

/**
 * Les rares noms qu'`Intl` donne sous une forme administrative ou abrégée
 * (« Hong Kong SAR China », « St. Vincent & Grenadines ») ; « & » et « St. »
 * sont, eux, développés pour tous.
 */
