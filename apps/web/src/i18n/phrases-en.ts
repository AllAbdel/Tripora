/**
 * L'anglais de la traduction au rendu (voir `traductionAuRendu.ts`).
 *
 * La clé est la phrase française telle qu'elle s'affiche, espaces resserrés ;
 * la valeur, sa traduction. Les motifs traduisent les phrases qui portent un
 * nombre ou un nom : ancrés (^…$), essayés dans l'ordre après les phrases
 * exactes ; une fonction peut renoncer (`null`) et laisser passer le suivant.
 *
 * Vocabulaire tenu partout : « trip » pour voyage, « wishes » pour les
 * envies, « vault » pour le coffre, « people » pour les participants, comme `textes.ts`.
 * Les montants gardent leur écriture européenne (« 1 800 € ») : ce sont ceux
 * que la personne paiera.
 *
 * Pour compléter : `pnpm --filter @tripora/web traductions:recolte` liste ce
 * qui reste en français à l'écran.
 */

/** Les pays du catalogue, en anglais : le navigateur connaît leur nom (Intl), il suffit du code. */
const PAYS_EN: Readonly<Record<string, string>> = (() => {
  const noms = typeof Intl !== 'undefined' && 'DisplayNames' in Intl ? new Intl.DisplayNames(['en'], { type: 'region' }) : null;
  const sortie: Record<string, string> = {};
  if (!noms) return sortie;
  for (const destination of DESTINATIONS) {
    const code = destination.countryCode?.toUpperCase();
    if (!code || sortie[destination.country]) continue;
    try {
      const nom = noms.of(code);
      if (nom && nom !== code) sortie[destination.country] = nom;
    } catch {
      // Un code inconnu de cette version du navigateur : le nom français reste.
    }
  }
  return sortie;
})();

