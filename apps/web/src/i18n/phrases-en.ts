/** Un morceau d'explication du classement (voir `distinction.ts` dans le cœur). */
function argument(morceau: string): string | null {
  const m = minuscule(morceau);
  if (ARGUMENTS[m]) return ARGUMENTS[m]!;
  let r: RegExpExecArray | null;
  if ((r = /^en tête de (\d+) points?$/u.exec(m))) return `in the lead by ${r[1]} point${r[1] === '1' ? '' : 's'}`;
  if ((r = /^(\S+) du classement, sans écart marquant avec les autres$/u.exec(m))) {
    const i = RANGS.indexOf(r[1]!);
    return `${i >= 0 ? RANGS_EN[i] : r[1]} in the ranking, with no clear gap from the others`;
  }
  if ((r = /^la plus chère, (.+) au-dessus de la moins chère$/u.exec(m))) return `the most expensive, ${r[1]} above the cheapest`;
  if ((r = /^elle devance le lot sur (.+) : (\d+)\/100 contre (\d+) en moyenne$/u.exec(m)) && CRITERES[r[1]!])
    return `ahead of the pack on ${CRITERES[r[1]!]}: ${r[2]}/100 vs ${r[3]} on average`;
  if ((r = /^au coude à coude avec les autres, avec un léger avantage sur (.+) \((\d+)\/100\)$/u.exec(m)) && CRITERES[r[1]!])
    return `neck and neck with the others, with a slight edge on ${CRITERES[r[1]!]} (${r[2]}/100)`;
  if ((r = /^aucun avantage net sur les autres ; sa meilleure carte reste (.+) \((\d+)\/100\)$/u.exec(m)) && CRITERES[r[1]!])
    return `no clear edge over the others; its best card is ${CRITERES[r[1]!]} (${r[2]}/100)`;
  if ((r = /^à surveiller : (.+) (\d+)\/100$/u.exec(m)) && CRITERES[r[1]!]) return `watch out: ${CRITERES[r[1]!]} ${r[2]}/100`;
  return null;
}


const nombre = (n: string, un: string, plusieurs: string) => (n === '1' ? un : plusieurs);

/**
 * Un complément venu des données (un titre, un nom) : sa traduction s'il en a
 * une, tel quel sinon — sauf s'il commence comme une phrase française
 * (« la carte », « cette dépense ») : mieux vaut alors le français entier
 * qu'une moitié de phrase en anglais.
 */
function complement(t: (francais: string) => string | null, texte: string): string | null {
  return t(texte) ?? (/^(?:le|la|les|l’|un|une|des|du|de|d’|ce|cet|cette|ces|mon|ma|mes|votre|vos|son|sa|ses|leur|leurs|sur|dans|avec|pour|à|au|aux|en|chez|par)\s/iu.test(texte) || /^(?:l’|d’)/iu.test(texte) ? null : texte);
}

/** Une durée « 2 h 05 », « 3 h », « 45 min » → « 2 hr 5 min », « 3 hr », « 45 min » ; null si ce n'en est pas une. */
function duree(texte: string): string | null {
  const r = /^(?:(\d+) h(?: (\d{2}))?|(\d+) min)$/u.exec(texte);
  if (!r) return null;
  if (r[3]) return `${r[3]} min`;
  return `${r[1]} hr${r[2] && r[2] !== '00' ? ` ${Number(r[2])} min` : ''}`;
}

/** « aujourd’hui », « hier », « il y a 3 jours », « le 8 sept. » : quand un prix a été vu. */
function quand(texte: string): string | null {
  if (texte === 'aujourd’hui') return 'today';
  if (texte === 'hier') return 'yesterday';
  const r = /^il y a (\d+) jours$/u.exec(texte);
  if (r) return `${r[1]} days ago`;
  const le = /^le (.+)$/u.exec(texte);
  return le ? `on ${le[1]}` : null;
}

/** « Relevé hier sur Aviasales », « Prix relevé le 8 sept. sur Aviasales, vendu par Kiwi, pour un départ le 12 oct. » */
function provenance(texte: string): string | null {
  const r = /^(Prix relevé|Relevé|relevé) (aujourd’hui|hier|il y a \d+ jours|le .+?) sur (.+?)(?:, vendu par (.+?))?(?:, pour un aller le (.+?) et un retour le (.+?)|, pour un départ le (.+?))?(\.?)$/u.exec(texte);
  if (!r) return null;
  const debut = { 'Prix relevé': 'Price checked', Relevé: 'Checked', relevé: 'checked' }[r[1]!];
  const site = r[3] === 'une source datée' ? 'a dated source' : r[3];
  const vendeur = r[4] ? `, sold by ${r[4]}` : '';
  const dates = r[5] ? `, for an outbound on ${r[5]} and a return on ${r[6]}` : r[7] ? `, for a departure on ${r[7]}` : '';
  return `${debut} ${quand(r[2]!)} on ${site}${vendeur}${dates}${r[8]}`;
}

